// --- Typst helpers ------------------------------------------------------------
const q = (s: string) => JSON.stringify(s); // a Typst string literal
/** Content from plain text: **bold** spans, line breaks, nothing else interpreted. */
function c(text: string | number | undefined | null): string {
  if (text === undefined || text === null || text === "") return "[]";
  const parts: string[] = [];
  String(text).split("\n").forEach((line, i) => {
    if (i > 0) parts.push("#linebreak()");
    line.split("**").forEach((seg, j) => {
      if (seg) parts.push(j % 2 ? `#strong(${q(seg)})` : `#${q(seg)}`);
    });
  });
  return `[${parts.join("")}]`;
}
function table(columns: string, header: string[], rows: (string | number | undefined)[][], opts: { cells?: "raw" } = {}): string {
  const cell = (x: string | number | undefined) => (opts.cells === "raw" ? String(x) : c(x as string));
  return `{
  set text(size: 0.8em)
  set par(justify: false)
  table(
    columns: ${columns},
    align: left,
    inset: (x: 4pt, y: 3pt),
    table.hline(),
    table.header(${header.map((h) => (h ? `[*${h}*]` : "[]")).join(", ")}),
    table.hline(),
${rows.map((r) => "    " + r.map(cell).join(", ") + ",").join("\n")}
    table.hline(),
  )
}`;
}
const fig = (body: string, caption: string, label?: string) =>
  `#figure(\n${body},\n  caption: ${c(caption)},\n)${label ? ` <${label}>` : ""}\n`;
const heading = (text: string) => `== ${text}\n`;
const para = (text: string) => `#${q(text)}\n`;
const HEAD = `// Generated by scripts/thesis-appendices.ts: do not edit by hand; re-run \`npm run appendices\`.\n#import "../../template.typ": shot\n#show figure: set block(breakable: true)\n\n`;
const write = (name: string, body: string) => {
  writeFileSync(join(outDir, `${name}.typ`), HEAD + body);
  console.log(`  ${name}.typ`);
};

