/**
 * Generates the data-heavy appendices of the thesis as Typst files, from the
 * same sources the study used, so that they stay correct when the study texts
 * or datasets change:
 *
 *   npm run appendices [-- <thesisDir>]     (default thesis)
 *
 * Writes <thesisDir>/appendices/generated/{protocol,tasks,questionnaires,
 * statistics,software,baselines}.typ. Text goes into Typst as string literals,
 * so file names and instructions need no escaping. The statistics appendix
 * reads analysis-out/report.md and results/strategies.csv (aggregated results
 * only); run `npm run analysis` first. "predicate" becomes "unified" and
 * "tutorial" becomes "practice", as in the thesis.
 */
