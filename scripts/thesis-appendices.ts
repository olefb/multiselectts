// --- Appendix E: statistical tables, from report.md ------------------------------------------
{
  const report = "analysis-out/report.md";
  let s = "";
  if (!existsSync(report)) {
    s += para("Run npm run analysis to generate the statistical tables.");
  } else {
    const relabel = (x: string) =>
      x
        .replace(/Predicate/g, "Unified")
        .replace(/predicate/g, "unified")
        .replace(/Tutorial/g, "Practice")
        .replace(/tutorial/g, "practice")
        .replace(/pred\.\/trad\./g, "unified/trad.")
        .replace(
          "Linear mixed model per task: log(time) ~ system × position + dataset + (1 | participant).",
          "A mixed model per task, checking the order of the systems: log time explained by the system, its position (first or second block) and the dataset, with each participant compared with themselves. The system × position column asks whether the difference between the systems depended on which came first.",
        )
        .replace(/\*\*/g, "")
        .replace(/\*(?=\s|$)/g, " *")
        .replace(/ +\*/g, " *");
    const lines = readFileSync(report, "utf8").split("\n");
    const skip = new Set(["Participants and data quality", "Strategies", "Method notes"]);
    s += para("The tables below are the output of the analysis (npm run analysis), relabelled for the thesis. In the tables, A to D are the tasks: A Keep what you have, B Context switch, C Rule with exceptions, D Keep and extend. Medians are given with the interquartile range in brackets; an asterisk marks p < .05.");
    let section = "";
    let sub = "";
    let caption = "";
    let lastCaption = "";
    let i = 0;
    while (i < lines.length) {
      const l = lines[i];
      if (l.startsWith("## ")) {
        section = l.slice(3).trim();
        sub = "";
        if (!skip.has(section)) s += heading(relabel(section));
        i++;
        continue;
      }
      if (l.startsWith("### ")) {
        sub = l.slice(4).trim();
        i++;
        continue;
      }
      if (skip.has(section) || section === "") {
        i++;
        continue;
      }
      if (l.startsWith("|")) {
        const rows: string[][] = [];
        while (i < lines.length && lines[i].startsWith("|")) {
          const cells = lines[i]
            .split("|")
            .slice(1, -1)
            .map((x) => relabel(x.trim()).replace(/^([A-D]): (Keep what you have|Context switch|Rule with exceptions|Keep and extend)$/, "$1"));
          if (!cells.every((x) => /^-+$/.test(x))) rows.push(cells);
          i++;
        }
        // drop columns that are empty in every body row, and d_z (the thesis reports r only)
        const keepCol = rows[0].map((h, j) => h !== "d_z" && rows.slice(1).some((r) => (r[j] ?? "") !== ""));
        const [head, ...body] = rows.map((r) => r.filter((_, j) => keepCol[j]));
        const cols = `(${head.map(() => "auto").join(", ")})`;
        let cap = relabel(caption || sub || section);
        if (cap === lastCaption) cap = `${cap}: ${head[0]}`;
        lastCaption = relabel(caption || sub || section);
        const label = cap.startsWith("Completion time (s) in Tasks B and C under different exclusion rules")
          ? "tab:threshold-time"
          : cap.startsWith("Gestures in Tasks B and C under different exclusion rules")
            ? "tab:threshold-gestures"
            : undefined;
        s += fig(table(section === "Hypotheses" ? "(auto, 1fr, 1fr, auto)" : cols, head, body), cap, label);
        caption = "";
        continue;
      }
      if (l.startsWith("![") || l.trim() === "") {
        i++;
        continue;
      }
      // a sentence of the report: keep it as a note under the section, and use it as the next table's caption if it ends with ":"
      const text = relabel(l.replace(/^- /, "").trim());
      if (text.endsWith(":")) caption = text.slice(0, -1);
      else s += para(text);
      i++;
    }
    // Strategies, from the CSV (the report's markdown header is incomplete)
    const csv = "analysis-out/results/strategies.csv";
    if (existsSync(csv)) {
      const [head, ...body] = readFileSync(csv, "utf8").trim().split("\n").map((l) => l.split(","));
      const feats = head.slice(2, -1);
      // one row per feature, one column per task and system (U = unified, T = traditional)
      const colsOf = body.map((r) => `${LETTER[r[0]] ?? r[0]}: ${r[1] === "predicate" ? "U" : "T"}`);
      const rows = feats.map((f, j) => [relabel(f), ...body.map((r) => `${Math.round(Number(r[j + 2]) * 100)}`)]);
      rows.push(["Attempts (n)", ...body.map((r) => r[r.length - 1])]);
      s += heading("Strategies");
      s += fig(
        table(`(1.6fr, ${colsOf.map(() => "auto").join(", ")})`, ["Feature", ...colsOf], rows),
        "Share of attempts (%) that used each feature, per task and system (all attempts; U = unified, T = traditional).",
        "tab:strategies",
      );
    }
  }
  write("statistics", s);
}

